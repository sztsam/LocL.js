import fs from "node:fs";
import path from "node:path";

export interface CompileOptions {
  /** Locales directory containing JSON files (default: "locales") */
  localesDir?: string;
  /** Output file path (default: "src/locales.compiled.ts") */
  output?: string;
  /** Output format: "ts" | "esm" | "cjs" | "json" (default: "ts") */
  format?: "ts" | "esm" | "cjs" | "json";
}

export interface CompileResult {
  outputFile: string;
  localesCount: number;
  keysCount: number;
}

export function compileTranslations(options: CompileOptions = {}): CompileResult {
  const localesDir = options.localesDir ?? "locales";
  const format = options.format ?? "ts";
  const defaultExt = format === "ts" ? "ts" : format === "json" ? "json" : "js";
  const outPath = options.output ?? `src/locales.compiled.${defaultExt}`;

  if (!fs.existsSync(localesDir)) {
    throw new Error(`[LocL/compile] Locales directory not found: "${localesDir}"`);
  }

  const files = fs.readdirSync(localesDir).filter((f) => f.endsWith(".json"));
  const bundles: Record<string, any> = {};
  let totalKeys = 0;

  for (const file of files) {
    const lang = file.replace(/\.json$/, "");
    const content = JSON.parse(fs.readFileSync(path.join(localesDir, file), "utf8"));
    bundles[lang] = content;
    totalKeys += Object.keys(content).length;
  }

  let code = "";
  if (format === "ts") {
    code = `// Auto-generated by LocL CLI (locl compile). Do not edit manually.\nexport const resources = ${JSON.stringify(bundles, null, 2)} as const;\nexport type AppResources = typeof resources;\nexport default resources;\n`;
  } else if (format === "esm") {
    code = `// Auto-generated by LocL CLI (locl compile). Do not edit manually.\nexport const resources = ${JSON.stringify(bundles, null, 2)};\nexport default resources;\n`;
  } else if (format === "cjs") {
    code = `// Auto-generated by LocL CLI (locl compile). Do not edit manually.\nmodule.exports = ${JSON.stringify(bundles, null, 2)};\n`;
  } else {
    code = JSON.stringify(bundles, null, 2) + "\n";
  }

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, code, "utf8");

  return {
    outputFile: outPath,
    localesCount: Object.keys(bundles).length,
    keysCount: totalKeys
  };
}
